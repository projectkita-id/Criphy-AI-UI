
import type { CaseStudyContext } from "../data/caseStudies";

// Supported learning phases.
export type LearningPhaseNumber = 1 | 2 | 3 | 4 | 5;

// A single question displayed to the student.
export interface AILearningQuestion {
  id: string;
  phase: LearningPhaseNumber;
  question: string;
  hint?: string;
}

// Data point used for physics graphs.
export interface AIMotionDataPoint {
  time: number;
  values: Record<string, number>;
}

// A dataset supplied by the backend.
// The backend must ensure that the data is scientifically valid.
export interface AILearningDataset {
  id: string;
  title: string;
  description?: string;
  xAxisLabel: string;
  yAxisLabel: string;
  series: {
    id: string;
    label: string;
    unit: string;
  }[];
  data: AIMotionDataPoint[];
}

// Content belonging to one learning phase.
export interface AILearningPhase {
  phase: LearningPhaseNumber;
  title: string;
  description: string;
  questions: AILearningQuestion[];
  dataset?: AILearningDataset;
}

// Generated cognitive-conflict case study.
export interface AIGeneratedCaseStudy {
  id: string;
  title: string;
  description: string;
  context: CaseStudyContext;
  topic: string;
  cognitiveConflict: string;
  phases: AILearningPhase[];
  generatedAt: string;
}

// Data sent when requesting a new case study.
export interface AICaseGenerationRequest {
  sessionId: string;
  moduleId: string;
  context: CaseStudyContext;
}

// Response returned after generation.
export interface AICaseGenerationResponse {
  success: boolean;
  caseStudy?: AIGeneratedCaseStudy;
  error?: string;
}

// Student's answer to an AI learning question.
export interface AILearningAnswer {
  questionId: string;
  answer: string;
  submittedAt: string;
}

// Data sent for adaptive learning feedback.
export interface AILearningFeedbackRequest {
  sessionId: string;
  caseStudyId: string;
  phase: LearningPhaseNumber;
  answer: AILearningAnswer;
}

// Feedback generated by the AI service.
export interface AILearningFeedbackResponse {
  success: boolean;
  feedback?: string;
  nextQuestion?: AILearningQuestion;
  phaseCompleted?: boolean;
  error?: string;
}